guiv2::ReadonlyMonoBitMap Ascii1608::GetChar(char32_t ch) const {
    if (ch <= ' ' || ch > '~') {
        // space for default
        return {8, 16, ascii1608_data};
    }
    return {8, 16, &ascii1608_data[(ch - ' ') * 16]};
}


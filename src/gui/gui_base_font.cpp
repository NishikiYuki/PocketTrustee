guiv2::ReadonlyMonoBitMap Digit32::GetChar(char32_t ch) const {
    if (ch < '0' || ch > '9') {
        return {0, 0, nullptr};
    }
    return {32, 16, &digit_32_data[(ch - '0') * 64]};
}

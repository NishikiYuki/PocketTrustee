StartupWindow::StartupWindow(Gui& host) : Window(host) {
    rect_.width = host.Width();
    rect_.height = host.Height();
}

void StartupWindow::OnCreate() {
    host_.Invalidate(true);
}

void StartupWindow::OnRender(Scheme& scheme) {
    constexpr Point2u origin = Point2u::CenterOrientedOrigin(13 * 16, 32, {296 / 2, 64});
    for (uint8_t i = 0; i < 13; i++) {
        ReadonlyMonoBitMap map{16, 32, &startup_font[access_table[i] * chr_size]};
        scheme.PasteFrom(map, origin + Point2u{static_cast<size_t>(i * 16), 0});
    }
    char vstr[32];
    int len = sprintf(vstr, "App Ver %u.%u", PocketTrustee::MVersion.major, PocketTrustee::MVersion.minor);
    if (len < 0) return;
    scheme.Text(std::string_view{vstr, static_cast<size_t>(len)}, base_font::Ascii1608::Get(), {2, 112});
}

void StartupWindow::OnEvent(const UiEvent& event) {
    if (event.bEvent == UiEvent::BasicEnter) {
        WindowRect rect = {
            Point2u::CenterOrientedOrigin(128, 96, {rect_.width / 2, rect_.height / 2}),
            128,
            96,
        };
        auto callback = [this, rect](int n) {
            std::string_view t;
            if (n == 1) {
                t = "Ok";
            }
            else {
                t = "Cancel";
            }
            auto wn = std::make_unique<extension::OptionWindow>(
                host_,
                rect,
                "Clicked!",
                t,
                "Ok",
                "Cancel",
                nullptr
            );
            host_.OpenWindow(std::move(wn));
        };
        auto wn = std::make_unique<extension::OptionWindow>(
            host_,
            rect,
            "Hello",
            "Hello World!",
            "Ok",
            "Cancel",
            std::move(callback)
        );
        host_.OpenWindow(std::move(wn));
    }
}
